export const LANGUAGES = [
  { code: 'uz', name: "O'zbekcha" },
  { code: 'ru', name: 'Русский' },
  { code: 'en', name: 'English' },
];

/** The language to use: the one asked for if we have it, else the browser's, else Uzbek. */
export function pickLanguage(...wanted) {
  for (const w of [...wanted, ...(navigator.languages || [])]) {
    const code = String(w || '').toLowerCase().split(/[-_]/)[0];
    if (STRINGS[code]) return code;
  }
  return 'uz';
}

export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.uz;
  return (key, vars = {}) => {
    const text = table[key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  };
}
